  /** Display order and names, the same as the Android app (ScreenTimeStore.kt, MainActivity.kt). */
  const SITES = {
    youtube: {
      name: 'YouTube',
      parts: [
        ['shorts', 'Shorts'],
        ['video', 'Videos'],
        ['other', 'Not watching'],
      ],
    },
    instagram: {
      name: 'Instagram',
      parts: [
        ['scrolling', 'Scrolling Reels'],
        ['normal', 'Posts & Stories'],
        ['chat', 'Chat'],
        ['other', 'Other'],
      ],
    },
  };
  const KEY = 'unreel-screen-time';
  const BADGE_KEY = 'unreel-screen-time-badge';
  const RETENTION_DAYS = 60;
  const MINUTE = 60_000;
  const TICK_MS = 1000;
  /** A longer gap between ticks means the page or the phone slept. */
  const MAX_TICK_MS = 2000;
  const IDLE_MS = 5 * MINUTE;
  const SAVE_EVERY_MS = 10_000;

  // ---- Pure parts (tested) -------------------------------------------------------------------

  function siteOf(hostname) {
    if (/(^|\.)youtube\.com$/.test(hostname)) return 'youtube';
    if (/(^|\.)instagram\.com$/.test(hostname)) return 'instagram';
    return null;
  }

  /** Which part of the site this page is. `playing`: a video is playing with sound. */
  function partOf(site, pathname, playing) {
    if (site === 'youtube') {
      if (/^\/shorts(\/|$)/.test(pathname)) return 'shorts';
      if (/^\/(watch\/?$|live\/)/.test(pathname) || playing) return 'video';
      return 'other';
    }
    if (/^\/reels(\/|$)/.test(pathname)) return 'scrolling';
    if (/^\/direct(\/|$)/.test(pathname)) return 'chat';
    if (pathname === '/' || /^\/(p|reel|stories)\//.test(pathname)) return 'normal';
    return 'other';
  }

  /** Local calendar day, yyyy-MM-dd, like the Android app. */
  function dayKey(ms) {
    const d = new Date(ms);
    const pad = (n) => String(n).padStart(2, '0');
    return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
  }

  /** { days: { 'yyyy-MM-dd': { part: ms } } }, from storage text; anything unreadable is empty. */
  function parse(raw) {
    try {
      const data = JSON.parse(raw);
      if (data && typeof data.days === 'object' && data.days !== null && !Array.isArray(data.days)) return { days: data.days };
    } catch {
      // Fall through.
    }
    return { days: {} };
  }

  function add(store, at, part, ms) {
    const day = dayKey(at);
    const parts = store.days[day] || (store.days[day] = {});
    parts[part] = (parts[part] || 0) + ms;
    return store;
  }

  /** Adds another store's times into `store` (a tab's unsaved time into what's saved). */
  function merge(store, other) {
    for (const [day, parts] of Object.entries(other.days)) {
      const into = store.days[day] || (store.days[day] = {});
      for (const [part, ms] of Object.entries(parts)) {
        if (typeof ms === 'number' && ms > 0) into[part] = (typeof into[part] === 'number' ? into[part] : 0) + ms;
      }
    }
    return store;
  }

  function prune(store, now) {
    const cutoff = dayKey(now - RETENTION_DAYS * 24 * 60 * MINUTE);
    for (const day of Object.keys(store.days)) if (day < cutoff) delete store.days[day];
    return store;
  }

  /** The last `n` days, oldest first, including empty ones: [{ date, parts }]. */
  function lastDays(store, n, now) {
    const out = [];
    const d = new Date(now);
    d.setHours(12, 0, 0, 0); // Midday, so stepping back a day never trips over a DST change.
    d.setDate(d.getDate() - (n - 1));
    for (let i = 0; i < n; i++) {
      const date = dayKey(d.getTime());
      out.push({ date, parts: store.days[date] || {} });
      d.setDate(d.getDate() + 1);
    }
    return out;
  }

  /** "0 min", "under 1 min", "45 min", "2 h", "1 h 12 min". Same as the Android app. */
  function durationText(ms) {
    if (!(ms > 0)) return '0 min';
    const minutes = Math.floor(ms / MINUTE);
    if (minutes === 0) return 'under 1 min';
    const h = Math.floor(minutes / 60);
    const m = minutes % 60;
    if (h === 0) return `${m} min`;
    return m === 0 ? `${h} h` : `${h} h ${m} min`;
  }

  if (globalThis.__UNREEL_TEST__) {
    globalThis.__unreelScreenTime = { SITES, siteOf, partOf, dayKey, parse, add, merge, prune, lastDays, durationText };
    return;
  }

  const site = siteOf(location.hostname);
  if (!site) return;

  // ---- Counting ------------------------------------------------------------------------------

  let unsaved = { days: {} };
  let lastTick = Date.now();
  let lastInput = Date.now();
  let lastSave = Date.now();

  function read() {
    try {
      return parse(localStorage.getItem(KEY));
    } catch {
      return { days: {} };
    }
  }

  /** Saved time plus this tab's unsaved time. */
  function current() {
    return merge(read(), unsaved);
  }

  function save() {
    lastSave = Date.now();
    if (Object.keys(unsaved.days).length === 0) return;
    const store = prune(current(), Date.now());
    try {
      localStorage.setItem(KEY, JSON.stringify(store));
      unsaved = { days: {} };
    } catch {
      // Storage full or blocked (some private modes): keep counting in memory for this visit.
    }
  }

  function playingWithSound() {
    for (const video of document.querySelectorAll('video')) {
      if (!video.paused && !video.ended && !video.muted && video.volume > 0 && video.readyState > 2) return true;
    }
    return false;
  }

  const touchScreen = typeof matchMedia === 'function' && matchMedia('(pointer: coarse)').matches;

  function inUse(now, playing) {
    if (document.visibilityState !== 'visible') return false;
    if (playing) return true;
    // On a computer, only the focused window counts, so two tabs side by side aren't counted twice.
    return (touchScreen || document.hasFocus()) && now - lastInput < IDLE_MS;
  }

  let ticks = 0;
  function tick() {
    const now = Date.now();
    const elapsed = Math.min(Math.max(now - lastTick, 0), MAX_TICK_MS);
    lastTick = now;
    const playing = playingWithSound();
    if (elapsed > 0 && inUse(now, playing)) add(unsaved, now, partOf(site, location.pathname, playing), elapsed);
    if (now - lastSave >= SAVE_EVERY_MS) save();
    ticks++;
    if (ui) {
      if (!ui.host.isConnected && document.documentElement) document.documentElement.appendChild(ui.host);
      if (!ui.panel.hidden) renderPanel();
      else if (ticks % 5 === 0) renderBadge();
    }
  }

  const noteInput = () => {
    lastInput = Date.now();
  };
  for (const type of ['pointerdown', 'keydown', 'wheel', 'touchstart', 'scroll']) {
    document.addEventListener(type, noteInput, { capture: true, passive: true });
  }
  document.addEventListener('visibilitychange', () => {
    lastTick = Date.now(); // Time spent hidden is never counted.
    if (document.visibilityState === 'hidden') save();
  });
  window.addEventListener('pagehide', save);
  setInterval(tick, TICK_MS);


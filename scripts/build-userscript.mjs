#!/usr/bin/env node
/**
 * Builds iphone/unreel.user.js from the Safari extension's sources, so the userscript and the
 * extension always behave the same:
 *
 *   targets/safari/assets/content.css  → injected as a <style> at document start
 *   targets/safari/assets/content.js   → URL rewriting for full loads and in-page navigation
 *
 * It also writes iphone/unreel.meta.js (the header only), which the Userscripts app polls to
 * offer updates. Raise `userscript.version` in package.json whenever the script changes, or
 * installed copies won't update.
 *
 *   node scripts/build-userscript.mjs          # write the file
 *   node scripts/build-userscript.mjs --check  # CI: exit 1 if it's stale
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const css = readFileSync(join(root, 'targets/safari/assets/content.css'), 'utf8');
const js = readFileSync(join(root, 'targets/safari/assets/content.js'), 'utf8');
const out = join(root, 'iphone/unreel.user.js');
const metaOut = join(root, 'iphone/unreel.meta.js');
const version = pkg.userscript?.version ?? pkg.version;
const updateBase = pkg.userscript?.updateBase;

const header = `// ==UserScript==
// @name         Unreel: no Shorts, no Reels
// @namespace    unreel
// @version      ${version}
// @description  Removes YouTube Shorts and Instagram Reels from the websites. A Short or Reel someone sends you opens as a normal video or post; the swipe feeds are gone.
// @match        *://*.youtube.com/*
// @match        *://*.instagram.com/*
// @run-at       document-start
// @inject-into  content
// @grant        none
// @noframes${updateBase ? `
// @updateURL    ${updateBase}unreel.meta.js
// @downloadURL  ${updateBase}unreel.user.js` : ''}
// ==/UserScript==

// GENERATED by scripts/build-userscript.mjs from targets/safari/assets/content.{css,js}.
// Edit those files, then run \`npm run build:userscript\`.
`;

const body = `
(() => {
  // Hide the shelves, tabs and links that lead into Shorts and Reels.
  const css = ${JSON.stringify(css)};
  const addStyle = () => {
    if (document.getElementById('unreel-style')) return true;
    const root = document.head || document.documentElement;
    if (!root) return false; // At document-start the page may not have a root element yet.
    const style = document.createElement('style');
    style.id = 'unreel-style';
    style.textContent = css;
    root.appendChild(style);
    return true;
  };
  if (!addStyle()) {
    const observer = new MutationObserver(() => addStyle() && observer.disconnect());
    observer.observe(document, { childList: true, subtree: true });
  }
  // YouTube and Instagram rebuild parts of the page as you navigate; put the style back if it's dropped.
  setInterval(addStyle, 1000);
})();

${js.trim()}
`;

const content = header + body;
const meta = header.slice(0, header.indexOf('// ==/UserScript==')) + '// ==/UserScript==\n';
const check = process.argv.includes('--check');

const files = [
  [out, content],
  [metaOut, meta],
];
if (check) {
  const stale = files.filter(([path, text]) => !existsSync(path) || readFileSync(path, 'utf8') !== text);
  if (stale.length) {
    for (const [path] of stale) console.error(`stale: ${path.slice(root.length + 1)} (run npm run build:userscript)`);
    process.exit(1);
  }
} else {
  mkdirSync(dirname(out), { recursive: true });
  for (const [path, text] of files) {
    writeFileSync(path, text);
    console.log(`wrote ${path.slice(root.length + 1)}`);
  }
}
